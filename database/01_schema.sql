-- 智能停车场管理系统：数据库结构
-- PostgreSQL 17
-- 执行目标：空的 smart_parking 数据库

BEGIN;

CREATE TABLE user_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username VARCHAR(50) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(50) NOT NULL,
    role VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_user_account PRIMARY KEY (id),
    CONSTRAINT uk_user_account_username UNIQUE (username),
    CONSTRAINT ck_user_account_username
        CHECK (username = LOWER(BTRIM(username)) AND BTRIM(username) <> ''),
    CONSTRAINT ck_user_account_password_hash CHECK (BTRIM(password_hash) <> ''),
    CONSTRAINT ck_user_account_display_name CHECK (BTRIM(display_name) <> ''),
    CONSTRAINT ck_user_account_role CHECK (role IN ('ADMIN', 'OWNER')),
    CONSTRAINT ck_user_account_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE TABLE vehicle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    owner_user_id BIGINT NOT NULL,
    license_plate VARCHAR(15) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_vehicle PRIMARY KEY (id),
    CONSTRAINT uk_vehicle_license_plate UNIQUE (license_plate),
    CONSTRAINT fk_vehicle_owner
        FOREIGN KEY (owner_user_id) REFERENCES user_account (id) ON DELETE RESTRICT,
    CONSTRAINT ck_vehicle_license_plate
        CHECK (license_plate = UPPER(BTRIM(license_plate)) AND BTRIM(license_plate) <> ''),
    CONSTRAINT ck_vehicle_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE TABLE parking_lot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    lot_code VARCHAR(30) NOT NULL,
    lot_name VARCHAR(100) NOT NULL,
    address VARCHAR(255) NOT NULL,
    description VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_parking_lot PRIMARY KEY (id),
    CONSTRAINT uk_parking_lot_code UNIQUE (lot_code),
    CONSTRAINT ck_parking_lot_code
        CHECK (lot_code = UPPER(BTRIM(lot_code)) AND BTRIM(lot_code) <> ''),
    CONSTRAINT ck_parking_lot_name CHECK (BTRIM(lot_name) <> ''),
    CONSTRAINT ck_parking_lot_address CHECK (BTRIM(address) <> ''),
    CONSTRAINT ck_parking_lot_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE TABLE parking_area (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    parking_lot_id BIGINT NOT NULL,
    area_code VARCHAR(20) NOT NULL,
    area_name VARCHAR(50) NOT NULL,
    description VARCHAR(255),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_parking_area PRIMARY KEY (id),
    CONSTRAINT uk_parking_area_lot_code UNIQUE (parking_lot_id, area_code),
    CONSTRAINT fk_parking_area_lot
        FOREIGN KEY (parking_lot_id) REFERENCES parking_lot (id) ON DELETE RESTRICT,
    CONSTRAINT ck_parking_area_code
        CHECK (area_code = UPPER(BTRIM(area_code)) AND BTRIM(area_code) <> ''),
    CONSTRAINT ck_parking_area_name CHECK (BTRIM(area_name) <> ''),
    CONSTRAINT ck_parking_area_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE TABLE parking_space (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    area_id BIGINT NOT NULL,
    space_code VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'FREE',
    description VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_parking_space PRIMARY KEY (id),
    CONSTRAINT uk_parking_space_area_code UNIQUE (area_id, space_code),
    CONSTRAINT fk_parking_space_area
        FOREIGN KEY (area_id) REFERENCES parking_area (id) ON DELETE RESTRICT,
    CONSTRAINT ck_parking_space_code
        CHECK (space_code = UPPER(BTRIM(space_code)) AND BTRIM(space_code) <> ''),
    CONSTRAINT ck_parking_space_status CHECK (status IN ('FREE', 'OCCUPIED', 'DISABLED'))
);

CREATE TABLE fee_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    parking_lot_id BIGINT NOT NULL,
    rule_name VARCHAR(50) NOT NULL,
    free_minutes INTEGER NOT NULL DEFAULT 30,
    billing_unit_minutes INTEGER NOT NULL DEFAULT 60,
    unit_price NUMERIC(10, 2) NOT NULL DEFAULT 5.00,
    max_fee_per_24h NUMERIC(10, 2) NOT NULL DEFAULT 50.00,
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    effective_from TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    effective_to TIMESTAMPTZ,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_fee_rule PRIMARY KEY (id),
    CONSTRAINT fk_fee_rule_lot
        FOREIGN KEY (parking_lot_id) REFERENCES parking_lot (id) ON DELETE RESTRICT,
    CONSTRAINT fk_fee_rule_creator
        FOREIGN KEY (created_by) REFERENCES user_account (id) ON DELETE RESTRICT,
    CONSTRAINT ck_fee_rule_name CHECK (BTRIM(rule_name) <> ''),
    CONSTRAINT ck_fee_rule_values CHECK (
        free_minutes >= 0
        AND billing_unit_minutes > 0
        AND unit_price >= 0
        AND max_fee_per_24h >= 0
    ),
    CONSTRAINT ck_fee_rule_effective_time
        CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CONSTRAINT ck_fee_rule_active_time
        CHECK (NOT is_active OR effective_to IS NULL)
);

CREATE TABLE parking_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    record_no VARCHAR(32) NOT NULL,
    parking_lot_id BIGINT NOT NULL,
    vehicle_id BIGINT,
    license_plate VARCHAR(15) NOT NULL,
    parking_space_id BIGINT NOT NULL,
    fee_rule_id BIGINT NOT NULL,
    entry_admin_id BIGINT NOT NULL,
    exit_admin_id BIGINT,
    entry_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    exit_time TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL DEFAULT 'PARKING',
    abnormal_reason VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_parking_record PRIMARY KEY (id),
    CONSTRAINT uk_parking_record_no UNIQUE (record_no),
    CONSTRAINT fk_parking_record_lot
        FOREIGN KEY (parking_lot_id) REFERENCES parking_lot (id) ON DELETE RESTRICT,
    CONSTRAINT fk_parking_record_vehicle
        FOREIGN KEY (vehicle_id) REFERENCES vehicle (id) ON DELETE RESTRICT,
    CONSTRAINT fk_parking_record_space
        FOREIGN KEY (parking_space_id) REFERENCES parking_space (id) ON DELETE RESTRICT,
    CONSTRAINT fk_parking_record_fee_rule
        FOREIGN KEY (fee_rule_id) REFERENCES fee_rule (id) ON DELETE RESTRICT,
    CONSTRAINT fk_parking_record_entry_admin
        FOREIGN KEY (entry_admin_id) REFERENCES user_account (id) ON DELETE RESTRICT,
    CONSTRAINT fk_parking_record_exit_admin
        FOREIGN KEY (exit_admin_id) REFERENCES user_account (id) ON DELETE RESTRICT,
    CONSTRAINT ck_parking_record_no CHECK (BTRIM(record_no) <> ''),
    CONSTRAINT ck_parking_record_license_plate
        CHECK (license_plate = UPPER(BTRIM(license_plate)) AND BTRIM(license_plate) <> ''),
    CONSTRAINT ck_parking_record_status CHECK (status IN ('PARKING', 'COMPLETED', 'ABNORMAL')),
    CONSTRAINT ck_parking_record_times CHECK (exit_time IS NULL OR exit_time >= entry_time),
    CONSTRAINT ck_parking_record_state_fields CHECK (
        (
            status = 'PARKING'
            AND exit_time IS NULL
            AND exit_admin_id IS NULL
            AND abnormal_reason IS NULL
        )
        OR (
            status = 'COMPLETED'
            AND exit_time IS NOT NULL
            AND exit_admin_id IS NOT NULL
        )
        OR (
            status = 'ABNORMAL'
            AND exit_time IS NOT NULL
            AND exit_admin_id IS NOT NULL
            AND BTRIM(COALESCE(abnormal_reason, '')) <> ''
        )
    )
);

CREATE TABLE payment_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    payment_no VARCHAR(32) NOT NULL,
    parking_record_id BIGINT NOT NULL,
    amount_due NUMERIC(10, 2) NOT NULL,
    amount_paid NUMERIC(10, 2) NOT NULL,
    payment_method VARCHAR(20) NOT NULL,
    payment_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    handled_by BIGINT NOT NULL,
    remark VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_payment_record PRIMARY KEY (id),
    CONSTRAINT uk_payment_record_no UNIQUE (payment_no),
    CONSTRAINT uk_payment_record_parking UNIQUE (parking_record_id),
    CONSTRAINT fk_payment_record_parking
        FOREIGN KEY (parking_record_id) REFERENCES parking_record (id) ON DELETE RESTRICT,
    CONSTRAINT fk_payment_record_handler
        FOREIGN KEY (handled_by) REFERENCES user_account (id) ON DELETE RESTRICT,
    CONSTRAINT ck_payment_record_no CHECK (BTRIM(payment_no) <> ''),
    CONSTRAINT ck_payment_record_amounts CHECK (amount_due >= 0 AND amount_paid >= 0),
    CONSTRAINT ck_payment_record_method
        CHECK (payment_method IN ('CASH', 'ELECTRONIC', 'FREE_RELEASE')),
    CONSTRAINT ck_payment_record_free_release CHECK (
        payment_method <> 'FREE_RELEASE'
        OR (amount_paid = 0 AND BTRIM(COALESCE(remark, '')) <> '')
    )
);

-- 每个停车场最多只有一条当前生效的收费规则。
CREATE UNIQUE INDEX uk_fee_rule_one_active_per_lot
    ON fee_rule (parking_lot_id)
    WHERE is_active;

-- 同一车牌、同一车位在任意时刻最多只有一条停车中记录。
CREATE UNIQUE INDEX uk_parking_record_active_plate
    ON parking_record (license_plate)
    WHERE status = 'PARKING';

CREATE UNIQUE INDEX uk_parking_record_active_space
    ON parking_record (parking_space_id)
    WHERE status = 'PARKING';

-- 常用查询索引。
CREATE INDEX idx_vehicle_owner_status
    ON vehicle (owner_user_id, status);

CREATE INDEX idx_parking_area_lot_status_code
    ON parking_area (parking_lot_id, status, area_code);

CREATE INDEX idx_parking_space_area_status_code
    ON parking_space (area_id, status, space_code);

CREATE INDEX idx_fee_rule_lot_active
    ON fee_rule (parking_lot_id, is_active);

CREATE INDEX idx_parking_record_lot_status
    ON parking_record (parking_lot_id, status);

CREATE INDEX idx_parking_record_lot_entry_time
    ON parking_record (parking_lot_id, entry_time);

CREATE INDEX idx_parking_record_license_plate_entry_time
    ON parking_record (license_plate, entry_time DESC);

CREATE INDEX idx_parking_record_vehicle_entry_time
    ON parking_record (vehicle_id, entry_time DESC)
    WHERE vehicle_id IS NOT NULL;

CREATE INDEX idx_parking_record_exit_time
    ON parking_record (exit_time)
    WHERE exit_time IS NOT NULL;

CREATE INDEX idx_payment_record_payment_time
    ON payment_record (payment_time);

CREATE INDEX idx_payment_record_handler
    ON payment_record (handled_by);

COMMENT ON TABLE user_account IS '管理员与车主账号';
COMMENT ON TABLE vehicle IS '车主绑定的车辆';
COMMENT ON TABLE parking_lot IS '系统管理的停车场';
COMMENT ON TABLE parking_area IS '停车场内的区域';
COMMENT ON TABLE parking_space IS '区域内的停车位及实时状态';
COMMENT ON TABLE fee_rule IS '停车场收费规则历史';
COMMENT ON TABLE parking_record IS '一次车辆入场到离场的停车过程';
COMMENT ON TABLE payment_record IS '停车结算记录';

COMMIT;
